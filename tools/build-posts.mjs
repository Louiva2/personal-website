// Writes blog/<slug>/index.html for every post in js/posts.js, from tools/post-template.html.
// Each post gets its own URL whose raw HTML already carries the title, summary and share-preview
// tags, since link-preview crawlers do not run JavaScript. The post is still rendered in the browser.
// A post in a series gets that series marked as the current nav item. The script also checks the
// series data in js/posts.js: known series, and no issue number used twice, planned ones included.
//
// A post whose entry carries en: { title, summary } also gets en/blog/<slug>/index.html, from
// tools/post-template.en.html; its English Markdown is posts/en/<slug>.md. The two pages point at
// each other. The English names and decks of the series are checked against the pages under en/.
//
// A post marked unlisted: true still gets its pages, with <meta name="robots" content="noindex, nofollow">
// in the head; js/site.js leaves it out of every list. It takes no issue number and no ledger.
//
//   node tools/build-posts.mjs           write the pages (Node 18+, no dependencies)
//   node tools/build-posts.mjs --check   write nothing; exit 1 if a page is missing or stale
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

// The published address. Canonical and og:url are built from it; change it here if the site moves.
const BASE_URL = "https://louiva2.github.io/personal-website/";
// Same slug rule as js/site.js. A slug becomes a directory and a fetch URL; nothing else gets through.
const SLUG = /^[a-z0-9-]+$/;
// First words of the comment at the top of every generated page.
const MARK = "<!-- Generated by tools/build-posts.mjs";
// What a planned issue of a series can be: being written, or only planned.
const STATUSES = ["writing", "planned"];
// Where the English pages live, under the site root.
const EN_DIR = "en/";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(`build-posts: ${message}`);
  process.exit(1);
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[ch]));
}

// js/posts.js is the one place post metadata lives. Run it in a sandbox rather than parse it.
function readSite() {
  const sandbox = {};
  vm.runInNewContext(readFileSync(join(repo, "js/posts.js"), "utf8"), sandbox, { filename: "js/posts.js" });
  const posts = sandbox.SITE_POSTS;
  if (!Array.isArray(posts)) fail("js/posts.js must set globalThis.SITE_POSTS to an array");
  const series = sandbox.SITE_SERIES ?? {};
  if (typeof series !== "object" || Array.isArray(series)) fail("js/posts.js: SITE_SERIES must be an object");

  // Issue numbers taken in each series, by planned issues and by posts alike.
  const taken = {};
  const claim = (key, no, where) => {
    if (!Number.isInteger(no) || no < 0) fail(`${where}: no must be a whole number, 0 or more`);
    if (taken[key].has(no)) fail(`${where}: no ${no} is used twice in series "${key}"`);
    taken[key].add(no);
  };
  for (const [key, entry] of Object.entries(series)) {
    const where = `js/posts.js, series "${key}"`;
    if (!SLUG.test(key)) fail(`${where}: the key must match ${SLUG}`);
    for (const field of ["title", "en", "path", "deck"]) {
      if (typeof entry?.[field] !== "string" || !entry[field].trim()) fail(`${where}: ${field} is missing`);
    }
    if (!/^[a-z0-9-]+\/$/.test(entry.path)) fail(`${where}: path must be one directory with a trailing slash, like "weekly/"`);
    if (!existsSync(join(repo, entry.path, "index.html"))) fail(`${where}: ${entry.path}index.html does not exist`);
    // The series page writes its name, English line and deck by hand; keep them the same as here.
    const page = readFileSync(join(repo, entry.path, "index.html"), "utf8");
    for (const field of ["title", "en", "deck"]) {
      if (!page.includes(escapeHtml(entry[field]))) fail(`${where}: ${entry.path}index.html does not contain the ${field} "${entry[field]}"`);
    }
    // The same for the English page of the series, which shows the Chinese name above the English one.
    for (const field of ["titleEn", "deckEn"]) {
      if (typeof entry[field] !== "string" || !entry[field].trim()) fail(`${where}: ${field} is missing`);
    }
    if (typeof (entry.unitEn ?? "") !== "string") fail(`${where}: unitEn must be text`);
    const enPath = `${EN_DIR}${entry.path}index.html`;
    if (!existsSync(join(repo, enPath))) fail(`${where}: ${enPath} does not exist`);
    const enPage = readFileSync(join(repo, enPath), "utf8");
    for (const field of ["title", "titleEn", "deckEn"]) {
      if (!enPage.includes(escapeHtml(entry[field]))) fail(`${where}: ${enPath} does not contain the ${field} "${entry[field]}"`);
    }
    if (!Array.isArray(entry.planned ?? [])) fail(`${where}: planned must be an array`);
    taken[key] = new Set();
    for (const item of entry.planned ?? []) {
      const at = `${where}, planned no ${JSON.stringify(item?.no)}`;
      claim(key, item?.no, at);
      if (!STATUSES.includes(item.status)) fail(`${at}: status must be one of ${STATUSES.join(", ")}`);
      for (const field of ["title", "note", "titleEn", "noteEn"]) {
        if (typeof (item[field] ?? "") !== "string") fail(`${at}: ${field} must be text`);
      }
    }
  }

  const seen = new Set();
  for (const post of posts) {
    const where = `js/posts.js, slug ${JSON.stringify(post && post.slug)}`;
    if (typeof post?.slug !== "string" || !SLUG.test(post.slug)) fail(`${where}: the slug must match ${SLUG}`);
    if (seen.has(post.slug)) fail(`${where}: the slug is used twice`);
    seen.add(post.slug);
    for (const key of ["title", "summary"]) {
      if (typeof post[key] !== "string" || !post[key].trim()) fail(`${where}: ${key} is missing`);
    }
    const day = new Date(`${post.date}T00:00:00Z`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(post.date) || Number.isNaN(day.getTime()) || day.toISOString().slice(0, 10) !== post.date) {
      fail(`${where}: date must be a real date written YYYY-MM-DD`);
    }
    if (!existsSync(join(repo, "posts", `${post.slug}.md`))) fail(`${where}: posts/${post.slug}.md does not exist`);
    if (post.en !== undefined) {
      for (const key of ["title", "summary"]) {
        if (typeof post.en?.[key] !== "string" || !post.en[key].trim()) fail(`${where}: en.${key} is missing`);
      }
      if (!existsSync(join(repo, "posts", "en", `${post.slug}.md`))) fail(`${where}: en is set but posts/en/${post.slug}.md does not exist`);
    }
    if (post.unlisted !== undefined && post.unlisted !== true) fail(`${where}: unlisted must be true or left out`);
    if (post.unlisted) {
      // Not in any list yet, so it holds no issue number and adds no ledger row. To publish it,
      // delete unlisted and give it a no.
      if (post.no !== undefined) fail(`${where}: an unlisted post takes no issue number; drop no`);
      if (post.ledger !== undefined) fail(`${where}: an unlisted post takes no ledger`);
      if (post.series !== undefined && !Object.hasOwn(series, post.series)) {
        fail(`${where}: series must be one of ${Object.keys(series).join(", ") || "(none defined)"}`);
      }
      continue;
    }
    if (post.series === undefined) {
      if (post.no !== undefined) fail(`${where}: no is set but series is not`);
      if (post.ledger !== undefined) fail(`${where}: ledger is set but series is not`);
      continue;
    }
    if (!Object.hasOwn(series, post.series)) {
      fail(`${where}: series must be one of ${Object.keys(series).join(", ") || "(none defined)"}`);
    }
    claim(post.series, post.no, where);
    for (const row of post.ledger === undefined ? [] : [post.ledger].flat()) {
      for (const key of ["model", "gpu", "precision", "unit"]) {
        if (typeof row?.[key] !== "string" || !row[key].trim()) fail(`${where}: ledger.${key} is missing`);
      }
      for (const key of ["bound", "measured"]) {
        if (typeof row[key] !== "number" || !Number.isFinite(row[key]) || row[key] <= 0) {
          fail(`${where}: ledger.${key} must be a number above 0`);
        }
      }
    }
  }
  return { posts, series };
}

// The nav item a post page marks as current: its series, or else the notes.
const NAV = ["weekly", "roofline", "blog"];

// The two sets of post pages. dir is where the pages go; an English page exists only for a post with en.
const LANGS = {
  zh: {
    dir: "blog/",
    template: "tools/post-template.html",
    has: () => true,
    text: (post) => ({ title: post.title, summary: post.summary }),
    // One share-preview picture for the whole site, per language.
    image: "assets/img/og.jpg",
  },
  en: {
    dir: `${EN_DIR}blog/`,
    template: "tools/post-template.en.html",
    has: (post) => post.en !== undefined,
    text: (post) => ({ title: post.en.title, summary: post.en.summary }),
    image: "assets/img/og-en.jpg",
  },
};

// The two addresses of a post, for rel="alternate". Empty when the post has no English page.
function alternates(post) {
  if (!LANGS.en.has(post)) return "";
  const zh = `${BASE_URL}blog/${post.slug}/`;
  const en = `${BASE_URL}${EN_DIR}blog/${post.slug}/`;
  return [
    `<link rel="alternate" hreflang="zh-CN" href="${escapeHtml(zh)}">`,
    `<link rel="alternate" hreflang="en" href="${escapeHtml(en)}">`,
    `<link rel="alternate" hreflang="x-default" href="${escapeHtml(zh)}">`,
  ].join("\n  ");
}

// The link in the nav to the same post in the other language. A Chinese post with no English
// version leads to the English list of notes instead.
function otherLanguage(lang, post) {
  if (lang === "en") return `<a class="lang" href="../../../blog/${post.slug}/" lang="zh-CN" hreflang="zh-CN">中文</a>`;
  const href = LANGS.en.has(post) ? `../../${EN_DIR}blog/${post.slug}/` : `../../${EN_DIR}blog/`;
  return `<a class="lang" href="${href}" lang="en" hreflang="en">EN</a>`;
}

function renderPage(lang, template, post) {
  const set = LANGS[lang];
  const values = {
    slug: post.slug,
    ...set.text(post),
    date: post.date,
    url: `${BASE_URL}${set.dir}${post.slug}/`,
    image: `${BASE_URL}${set.image}`,
  };
  const current = NAV.includes(post.series) ? post.series : "blog";
  // Raw placeholders, written into the page as they are: {{{nav:<item>}}} is the attribute for
  // the current nav item, or nothing; {{{alternates}}} and {{{lang}}} are the two functions above;
  // {{{robots}}} keeps an unlisted post out of search engines. Empty placeholders on a line of
  // their own take the line with them.
  const raw = {
    alternates: alternates(post),
    robots: post.unlisted ? '<meta name="robots" content="noindex, nofollow">' : "",
    lang: otherLanguage(lang, post),
  };
  return template
    .replace(/\{\{\{nav:([a-z]+)\}\}\}/g, (_, item) => {
      if (!NAV.includes(item)) fail(`${set.template}: unknown nav item {{{nav:${item}}}}`);
      return item === current ? ' aria-current="page"' : "";
    })
    .replace(/^[ \t]*\{\{\{(alternates|robots)\}\}\}\n/gm, (_, key) => (raw[key] ? `  ${raw[key]}\n` : ""))
    .replace(/\{\{\{(\w+)\}\}\}/g, (_, key) => {
      if (!(key in raw)) fail(`${set.template}: unknown placeholder {{{${key}}}}`);
      return raw[key];
    })
    .replace(/\{\{(\w+)\}\}/g, (_, key) => {
      if (!(key in values)) fail(`${set.template}: unknown placeholder {{${key}}}`);
      return escapeHtml(values[key]);
    });
}

const { posts } = readSite();
const problems = [];
let written = 0;

for (const [lang, set] of Object.entries(LANGS)) {
  const template = readFileSync(join(repo, set.template), "utf8");
  const mine = posts.filter(set.has);
  for (const post of mine) {
    const file = `${set.dir}${post.slug}/index.html`;
    const path = join(repo, file);
    const html = renderPage(lang, template, post);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === html) continue;
    if (checkOnly) {
      problems.push(`${file} is ${current === null ? "missing" : "out of date"}`);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, html);
    written += 1;
    console.log(`wrote ${file}`);
  }

  // A generated page whose post is no longer in js/posts.js, or no longer has this language, is stale as well.
  const slugs = new Set(mine.map((post) => post.slug));
  if (!existsSync(join(repo, set.dir))) continue;
  for (const entry of readdirSync(join(repo, set.dir), { withFileTypes: true })) {
    if (!entry.isDirectory() || slugs.has(entry.name)) continue;
    const file = `${set.dir}${entry.name}/index.html`;
    const path = join(repo, file);
    if (!existsSync(path) || !readFileSync(path, "utf8").includes(MARK)) continue;
    if (checkOnly) {
      problems.push(`${file} has no post in js/posts.js`);
      continue;
    }
    rmSync(path);
    if (!readdirSync(dirname(path)).length) rmSync(dirname(path), { recursive: true });
    written += 1;
    console.log(`removed ${file}`);
  }
}

if (problems.length) {
  for (const problem of problems) console.error(`build-posts: ${problem}`);
  fail("run `node tools/build-posts.mjs` and commit the result");
}
console.log(checkOnly || !written ? "build-posts: every post page is up to date" : `build-posts: ${written} file(s) changed`);
